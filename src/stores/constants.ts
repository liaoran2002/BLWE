/**
 * 播放相关的常量
 *
 * 散在 `playback` / `ui` 两处用（缓冲、预热、卡顿恢复、网络冷却），
 * 所以放在 stores 根目录而不是某个 store 里 —— 谁都能 import，谁也不拥有它。
 */
export const START_BUFFER_S = 5;
/** 播放中需要前方至少有多少秒余量才认为不会卡 */
export const LEAD_S = 3;
/**
 * 距片尾多少秒开始预热下一首
 *
 * 预热只跑「搜索 + 播放地址解析」两个接口（主进程有缓存），一般 1~3 秒就完；
 * 留 15 秒足够，也不至于太早 —— 太早拿到的播放地址可能已经过期。
 */
export const PREFETCH_AHEAD_S = 15;
/**
 * OV 模式下连续多少个条目失效就停止自动跳过
 *
 * 收藏夹里「已删除 / 私享 / 充电专属」的条目可能连成片，一条无效就跳下一条会让
 * 程序自己打出一串解析请求（某站 412 的经典触发方式），而且用户看到的是
 * 界面疯狂闪、不知道发生了什么。5 条足够越过零星失效，又不至于失控。
 */
export const OV_MAX_AUTO_SKIP = 5;
/**
 * 播放位置停住多久算「这条流不行了」
 *
 * 取 **8 秒**：正常网络波动、CDN 换节点都不会连着 8 秒一个字节都不来。
 * 命中后按分级链恢复（见 `recoverFromStall`）：换备用源 → 降清晰度 → 降 durl → 提示检查网络。
 */
export const STALL_MS = 8000;
/**
 * 卡顿恢复链里「降几档清晰度」之后就不降了，直接降到 durl
 *
 * 用户定的是 3 档：再往下降画面已经没法看了，不如直接退混流并提示检查网络。
 */
export const MAX_QUALITY_DROPS = 3;
/**
 * 手动改过**清晰度 / 音质**之后的冷却时间（毫秒）
 *
 * 用户要求 3 秒。切换清晰度会 `changeVideo(skipCache: true)` **重新解析地址**
 * （发请求），连点几下就是连着几个请求 —— 除了「请求期间禁用」之外，
 * 再加一道固定冷却，把「刚改完就想再改」这条路径也堵掉。
 */
export const QUALITY_COOLDOWN_MS = 3000;
/**
 * 「正在加载，先别点」这条提示的**节流间隔**（毫秒）
 *
 * 用户连点切歌时，每次都会走 `notifyNetBusy()` —— 不节流的话
 * toast 会一条接一条往外冒。2 秒内只提示一次足够表达「它在忙」。
 */
export const NET_BUSY_HINT_MS = 2000;
/**
 * 预热失败后的重试次数与间隔
 *
 * 心跳（`startEndWatch`）是**每秒**一次，所以光靠计数做不到「间隔 3 秒」——
 * 必须同时看时间戳，否则三次重试会在 3 秒内打完。
 *
 * 为什么是 3 次 / 3 秒：某站搜索偶发返回空（风控、抖动），隔几秒再试往往就好了；
 * 但连着 3 次都空基本就是「这首歌在某站真的没有」或「未登录导致结果被裁」，
 * 再试只是白烧网络（用户反馈过「日志刷几十行、界面卡住」）。
 */
export const WARM_MAX_TRIES = 3;
export const WARM_RETRY_DELAY_MS = 3000;
